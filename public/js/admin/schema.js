const RICH = 'You can use **bold**, *italic*, [link text](https://…), H_{2}O and Ca^{2+}. Leave a blank line between paragraphs.';
const INLINE = 'You can use **bold**, *italic*, [link text](https://…), subscripts like C_{3}N_{4} and superscripts like Ca^{2+}.';
const linkList = (label = 'Links', hint = '') => ({
  key: 'links',
  label,
  type: 'list',
  hint,
  addLabel: 'Add link',
  itemLabel: (l) => l.label || l.url || 'Link',
  fields: [
    { key: 'label', label: 'Label', type: 'text', required: true, max: 80, hint: 'For example Google Scholar, ORCID, LinkedIn' },
    { key: 'url', label: 'Address (URL)', type: 'url', required: true, max: 500 },
  ],
});
const periodRows = (key, label, { period = 'Period', title = 'Title', detail = 'Details', addLabel = 'Add entry' } = {}) => ({
  key,
  label,
  type: 'list',
  addLabel,
  itemLabel: (r) => [r.period, r.title].filter(Boolean).join(' · ') || 'New entry',
  fields: [
    { key: 'period', label: period, type: 'text', max: 40, hint: 'For example 2021 – 2026' },
    { key: 'title', label: title, type: 'text', required: true, max: 300 },
    { key: 'detail', label: detail, type: 'textarea', rows: 2, max: 1000, hint: INLINE },
  ],
});


